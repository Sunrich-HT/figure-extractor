RELATIVE_IMPORT = re.compile(r"^from \.\w* import ")
TOP_LEVEL_IMPORT = re.compile(r"^(?:import |from [A-Za-z_])")


def build() -> str:
    imports: list[str] = ["import argparse", "import sys"]
    body: list[str] = []

    for name in MODULES:
        source = (PKG / f"{name}.py").read_text(encoding="utf-8")
        chunk: list[str] = []
        pending_relative = False
        for line in source.splitlines():
            if line.startswith("from __future__ import"):
                continue
            if RELATIVE_IMPORT.match(line):
                # The module is inlined below instead; skip its continuation lines.
                pending_relative = not line.rstrip().endswith(")") and line.rstrip().endswith("(")
                continue
            if pending_relative:
                pending_relative = not line.strip().startswith(")")
                continue
            if TOP_LEVEL_IMPORT.match(line):
                if line not in imports:
                    imports.append(line)
                continue
            chunk.append(line)
        body.append(f"# --- from figure_extractor/{name}.py " + "-" * max(4, 48 - len(name)))
        body.append("\n".join(chunk).strip("\n"))

    parts = [HEADER, "\n".join(sorted(set(imports))), "", "\n\n\n".join(body), FOOTER]
    return "\n".join(parts).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="Exit non-zero if the committed file is out of date")
    args = ap.parse_args()

    generated = build()
    if args.check:
        current = DEST.read_text(encoding="utf-8") if DEST.exists() else ""
        if current != generated:
            print(f"{DEST.relative_to(ROOT)} is stale — run: python tools/build_standalone.py",
                  file=sys.stderr)
            return 1
        print(f"{DEST.relative_to(ROOT)} is up to date")
        return 0

    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(generated, encoding="utf-8")
    print(f"wrote {DEST.relative_to(ROOT)} ({len(generated.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
