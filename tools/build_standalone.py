#!/usr/bin/env python3
"""Stitch the PDF path into one dependency-free file.

Runtimes that cannot `pip install` — no network, no package index, no write
access to site-packages — can still crop figures if they have PyMuPDF, but only
if the tool arrives as a single file they can write and run. This generates that
file from the package so the two cannot drift apart.

    python tools/build_standalone.py            # regenerate
    python tools/build_standalone.py --check    # fail if the committed copy is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "figure_extractor"
DEST = ROOT / "standalone" / "figure_extractor_standalone.py"

# Dependency order: later modules may use names defined by earlier ones.
# html_extractor is deliberately absent — it needs beautifulsoup4.
MODULES = ["utils", "captions", "layout", "quality", "contact_sheet", "pdf_cropper"]

